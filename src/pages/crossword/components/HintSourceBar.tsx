// URL の行き先から出どころを決める（貼った時に印を合わせるため）
export function sourceOfUrl(input: string): HintSource {
  let host = "";
  try {
    host = new URL(input.trim()).hostname.replace(/^(www\.|m\.|music\.|mobile\.)/, "");
  } catch {
    return "link";
  }
  if (isYouTubeHost(input)) return "yt";
  if (host === "ameblo.jp" || host.endsWith(".ameba.jp") || host === "ameba.jp") return "ameblo";
  if (host === "x.com" || host === "twitter.com") return "x";
  if (host === "instagram.com" || host === "instagr.am") return "ig";
  return "link";
}

